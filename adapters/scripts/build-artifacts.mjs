#!/usr/bin/env node
// Publish the adapters with their npm dependencies. The installed plugin needs only
// Node and the resources in release-manifest.json; startup never installs packages.
import { createHash } from 'node:crypto'
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import { builtinModules } from 'node:module'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

import { build } from 'esbuild'

const ADAPTERS_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const REPO_ROOT = resolve(ADAPTERS_DIR, '..')
const GENERATED_DIR = join(ADAPTERS_DIR, 'generated')
const CHECK_ONLY = process.argv.includes('--check')
const HEADER = 'Generated by adapters/scripts/build-artifacts.mjs. Do not edit by hand.'
const ENTRIES = [
  ['cowart-service.mjs', 'service/bin/cowart-service.mjs'],
  ['cowart-codex-mcp.mjs', 'codex/bin/cowart-codex-mcp.mjs'],
  ['cowart-claude-mcp.mjs', 'claude/bin/cowart-claude-mcp.mjs'],
  ['cowart-listen.mjs', 'claude/bin/cowart-listen.mjs']
]
const NODE_MODULES = new Set(builtinModules.flatMap((name) => [name, `node:${name}`]))

// Build identity must be independent of the caller's test salt or installed plugin.
// identity.mjs hashes the same source for development and uses this constant in a
// bundle; both paths apply any runtime test salt after selecting the base value.
const previousRoot = process.env.COWART_ADAPTERS_ROOT
const previousSalt = process.env.COWART_SERVICE_BUILD_SALT
const previousSaltFile = process.env.COWART_SERVICE_BUILD_SALT_FILE
process.env.COWART_ADAPTERS_ROOT = ADAPTERS_DIR
delete process.env.COWART_SERVICE_BUILD_SALT
delete process.env.COWART_SERVICE_BUILD_SALT_FILE
let serviceBuild
try {
  const identity = await import(pathToFileURL(join(ADAPTERS_DIR, 'service/lib/identity.mjs')).href)
  serviceBuild = identity.codeFingerprint()
} finally {
  restoreEnv('COWART_ADAPTERS_ROOT', previousRoot)
  restoreEnv('COWART_SERVICE_BUILD_SALT', previousSalt)
  restoreEnv('COWART_SERVICE_BUILD_SALT_FILE', previousSaltFile)
}

const artifacts = new Map()
for (const [name, entry] of ENTRIES) {
  const result = await build({
    absWorkingDir: REPO_ROOT,
    entryPoints: [join(ADAPTERS_DIR, entry)],
    outfile: join(GENERATED_DIR, name),
    write: false,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    charset: 'utf8',
    minify: true,
    legalComments: 'eof',
    treeShaking: true,
    metafile: true,
    define: {
      __COWART_SERVICE_BUILD__: JSON.stringify(serviceBuild),
      // ws's optional native accelerators are unnecessary for local Chromium.
      // Fold these paths away so a clean install has no optional binary imports.
      'process.env.WS_NO_BUFFER_UTIL': '"1"',
      'process.env.WS_NO_UTF_8_VALIDATE': '"1"'
    },
    banner: {
      js: [
        `// ${HEADER}`,
        'import { createRequire as __cowartCreateRequire } from "node:module";',
        'import { fileURLToPath as __cowartFileURLToPath } from "node:url";',
        'const require = __cowartCreateRequire(import.meta.url);',
        'process.env.COWART_BUNDLED = "1";',
        'process.env.COWART_ADAPTERS_ROOT ||= __cowartFileURLToPath(new URL("../", import.meta.url));'
      ].join('\n')
    },
    plugins: [optionalBrowserDownloadPeers()],
    logLevel: 'warning'
  })
  for (const output of Object.values(result.metafile.outputs)) {
    const unresolved = output.imports.filter((item) => item.external && !NODE_MODULES.has(item.path))
    if (unresolved.length) {
      throw new Error(`${name} still needs external packages: ${unresolved.map((item) => item.path).join(', ')}`)
    }
  }
  artifacts.set(name, Buffer.from(result.outputFiles[0].contents))
}

const packageJson = JSON.parse(await readFile(join(ADAPTERS_DIR, 'package.json'), 'utf8'))
const resourcePaths = [
  '.codex-plugin/plugin.json',
  'adapters/package.json',
  'adapters/shared/empty-canvas.json',
  ...await filesIn('adapters/shared/web'),
  ...await filesIn('adapters/claude/web'),
  ...await filesIn('adapters/codex/web'),
  'mcp/generated/cowart-mcp.mjs',
  'mcp/generated/cowart-widget.html',
  'mcp/generated/release-manifest.json'
].sort()
const resources = Object.fromEntries(await Promise.all(resourcePaths.map(async (file) => [
  file, sha256(await readFile(join(REPO_ROOT, file)))
])))
artifacts.set('release-manifest.json', Buffer.from(`${JSON.stringify({
  version: packageJson.version,
  generatedBy: 'adapters/scripts/build-artifacts.mjs',
  node: '>=22.12.0',
  serviceBuild,
  artifacts: Object.fromEntries([...artifacts].map(([name, contents]) => [name, sha256(contents)])),
  resources
}, null, 2)}\n`))

if (CHECK_ONLY) {
  const stale = []
  for (const [name, expected] of artifacts) {
    const actual = await readFile(join(GENERATED_DIR, name)).catch((error) => {
      if (error.code === 'ENOENT') return null
      throw error
    })
    if (!actual?.equals(expected)) stale.push(name)
  }
  if (stale.length) {
    throw new Error(`Adapter artifacts are missing or stale: ${stale.join(', ')}. Run npm --prefix adapters run build:artifacts.`)
  }
  console.log('OK: Adapter release artifacts match the current source and resources.')
} else {
  await mkdir(GENERATED_DIR, { recursive: true })
  for (const [name, contents] of artifacts) await writeFile(join(GENERATED_DIR, name), contents)
  console.log(`Built ${artifacts.size} adapter artifacts (service ${serviceBuild}).`)
}

function restoreEnv(name, value) {
  if (value === undefined) delete process.env[name]
  else process.env[name] = value
}

function sha256(contents) {
  return createHash('sha256').update(contents).digest('hex')
}

function optionalBrowserDownloadPeers() {
  return {
    name: 'cowart-local-browser-only',
    setup(builder) {
      // Puppeteer includes browser installation APIs on its public class, so those
      // methods survive tree shaking. Cowart only launches installed Chromium;
      // these two optional peers are absent from its dependency lockfile. Preserve
      // Puppeteer's existing caught "not installed" behavior without asking the
      // installed plugin to resolve packages outside its release directory.
      builder.onResolve({ filter: /^(proxy-agent|yauzl)$/ }, (args) => ({ path: args.path, namespace: 'cowart-optional-browser-peer' }))
      builder.onLoad({ filter: /.*/, namespace: 'cowart-optional-browser-peer' }, (args) => ({
        contents: `const error = new Error(${JSON.stringify(`Optional browser-download package ${args.path} is not part of Cowart's local-browser runtime.`)}); error.code = 'ERR_MODULE_NOT_FOUND'; throw error;`,
        loader: 'js'
      }))
    }
  }
}

async function filesIn(repoRelativeDir) {
  const dir = join(REPO_ROOT, repoRelativeDir)
  const entries = await readdir(dir, { withFileTypes: true })
  const files = await Promise.all(entries.map(async (entry) => {
    const file = join(dir, entry.name)
    const repoPath = relative(REPO_ROOT, file).replaceAll('\\', '/')
    return entry.isDirectory() ? filesIn(repoPath) : [repoPath]
  }))
  return files.flat().sort()
}
